let activeRosterFilter = "all";
const rosterButtons = [...document.querySelectorAll("[data-roster-filter]")];
const rosterCards = [...document.querySelectorAll(".species-card")];

function updateRoster() {
  let count = 0;
  for (const card of rosterCards) {
    card.hidden = activeRosterFilter !== "all" && card.dataset.diet !== activeRosterFilter;
    if (!card.hidden) count++;
  }
  for (const button of rosterButtons) {
    button.setAttribute("aria-pressed", String(button.dataset.rosterFilter === activeRosterFilter));
  }
  const status = document.getElementById("roster-status");
  if (status) {
    status.textContent = getTranslation("roster_results").replace("{count}", count);
  }
}

for (const button of rosterButtons) {
  button.addEventListener("click", () => {
    activeRosterFilter = button.dataset.rosterFilter;
    updateRoster();
  });
}

function updateLocalizedA11y() {
  for (const [attribute, key] of [["aria-label", "i18nLabel"], ["alt", "i18nAlt"]]) {
    const selector = key === "i18nLabel" ? "[data-i18n-label]" : "[data-i18n-alt]";
    for (const element of document.querySelectorAll(selector)) {
      element.setAttribute(attribute, getTranslation(element.dataset[key]));
    }
  }
  updateRoster();
}

const gameplayDialog = document.getElementById("gameplay");
if (gameplayDialog?.showModal) {
  const video = gameplayDialog.querySelector("video");
  for (const link of document.querySelectorAll("[data-gameplay-link]")) {
    link.addEventListener("click", (event) => {
      if (event.button !== 0 || event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
      event.preventDefault();
      gameplayDialog.showModal();
      video.play().catch(() => {
        // Native controls remain available if the browser blocks playback.
      });
    });
  }
  gameplayDialog.addEventListener("close", () => video.pause());
}
