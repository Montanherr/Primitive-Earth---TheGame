// ==========================================================
// EMAIL VALIDATION
// ==========================================================

function isValidEmail(email) {

  const emailPattern =
    /^[^\s@]+@[^\s@]+\.[^\s@]+$/;


  return emailPattern.test(
    email
  );

}


// ==========================================================
// NORMALIZE EMAIL
// ==========================================================

function normalizeEmail(email) {

  return email
    .trim()
    .toLowerCase();

}


// ==========================================================
// LOCAL REGISTRATION
// ==========================================================

function emailWasRegistered(
  email
) {

  try {

    const registeredEmails =
      JSON.parse(
        localStorage.getItem(
          "primitive-earth-beta-emails"
        ) || "[]"
      );


    return registeredEmails.includes(
      email
    );

  } catch {

    return false;

  }

}


// ==========================================================
// SAVE LOCAL EMAIL
// ==========================================================

function saveRegisteredEmail(
  email
) {

  let registeredEmails =
    [];


  try {

    registeredEmails =
      JSON.parse(
        localStorage.getItem(
          "primitive-earth-beta-emails"
        ) || "[]"
      );

  } catch {

    registeredEmails =
      [];

  }


  if (
    !registeredEmails.includes(
      email
    )
  ) {

    registeredEmails.push(
      email
    );


    localStorage.setItem(
      "primitive-earth-beta-emails",
      JSON.stringify(
        registeredEmails
      )
    );

  }

}


// ==========================================================
