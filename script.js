// ==========================================================
// NEWSLETTER SUBMIT
// ==========================================================

newsletterForm.addEventListener(
  "submit",
  async (event) => {

    event.preventDefault();


    clearNewsletterMessage();


    // ======================================================
    // EMAIL
    // ======================================================

    const email =
      normalizeEmail(
        newsletterEmail.value
      );


    // ======================================================
    // HONEYPOT
    // ======================================================

    const honeyField =
      newsletterForm.querySelector(
        '[name="_honey"]'
      );


    if (
      honeyField?.value
    ) {

      return;

    }


    // ======================================================
    // VALID EMAIL
    // ======================================================

    if (
      !isValidEmail(
        email
      )
    ) {

      showNewsletterMessage(
        getTranslation(
          "form_invalid_email"
        ),
        "error"
      );


      newsletterEmail.focus();

      return;

    }


    // ======================================================
    // CONSENT
    // ======================================================

    if (
      !newsletterConsent.checked
    ) {

      showNewsletterMessage(
        getTranslation(
          "form_consent_required"
        ),
        "error"
      );


      newsletterConsent.focus();

      return;

    }


    // ======================================================
    // DUPLICATE
    // ======================================================

    if (
      emailWasRegistered(
        email
      )
    ) {

      showNewsletterMessage(
        getTranslation(
          "form_duplicate"
        ),
        "error"
      );


      return;

    }


    // ======================================================
    // CONFIG
    // ======================================================

    if (
      !destinationEmail ||
      destinationEmail.includes(
        "SEU_EMAIL"
      )
    ) {

      showNewsletterMessage(
        getTranslation(
          "form_config_error"
        ),
        "error"
      );


      return;

    }


    // ======================================================
    // LOADING
    // ======================================================

    setNewsletterLoading(
      true
    );


    showNewsletterMessage(
      getTranslation(
        "form_sending"
      ),
      "loading"
    );


    try {

      // ====================================================
      // FORM SUBMIT
      // ====================================================

      const response =
        await fetch(

          `https://formsubmit.co/ajax/${encodeURIComponent(
            destinationEmail
          )}`,

          {

            method:
              "POST",


            headers: {

              "Content-Type":
                "application/json",

              Accept:
                "application/json"

            },


            body:
              JSON.stringify({

                email:
                  email,


                language:
                  currentLanguage,


                consent:
                  "true",


                source:
                  window.location.href,


                registeredAt:
                  new Date()
                    .toISOString(),


                // ===========================================
                // EMAIL RECEIVED BY YOU
                // ===========================================

                _subject:
                  `Novo cadastro no Beta - Primitive Earth (${currentLanguage.toUpperCase()})`,


                // ===========================================
                // EMAIL RECEIVED BY USER
                // ===========================================

                _autoresponse:
                  getTranslation(
                    "confirmation_email"
                  ),


                // ===========================================
                // FORMSUBMIT
                // ===========================================

                _template:
                  "table",


                _captcha:
                  "false"

              })

          }

        );


      // ====================================================
      // RESPONSE
      // ====================================================

      let result =
        {};


      try {

        result =
          await response.json();

      } catch {

        result =
          {};

      }


      if (
        !response.ok
      ) {

        throw new Error(

          result.message ||
          "Form submission failed."

        );

      }


      // ====================================================
      // SAVE
      // ====================================================

      saveRegisteredEmail(
        email
      );


      // ====================================================
      // RESET
      // ====================================================

      newsletterForm.reset();


      // ====================================================
      // SUCCESS
      // ====================================================

      showNewsletterSuccess();


    } catch (error) {

      console.error(
        "Erro ao cadastrar e-mail:",
        error
      );


      showNewsletterMessage(
        getTranslation(
          "form_error"
        ),
        "error"
      );


    } finally {

      setNewsletterLoading(
        false
      );

    }

  }
);


