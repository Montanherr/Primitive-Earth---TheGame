// ==========================================================
// TRANSLATION
// ==========================================================

function getTranslation(key) {

  return (
    translations[currentLanguage]?.[key] ||
    translations.en[key] ||
    key
  );

}


// ==========================================================
// SET LANGUAGE
// ==========================================================

function setLanguage(lang) {

  const selected =
    supportedLanguages.includes(lang)
      ? lang
      : "en";


  currentLanguage =
    selected;


  // ========================================================
  // HTML LANG
  // ========================================================

  document.documentElement.lang =
    selected === "pt"
      ? "pt-BR"
      : selected;


  // ========================================================
  // TEXT
  // ========================================================

  document
    .querySelectorAll(
      "[data-i18n]"
    )
    .forEach(
      (element) => {

        const key =
          element.dataset.i18n;


        const value =
          translations[selected]?.[key];


        if (value) {

          element.textContent =
            value;

        }

      }
    );


  // ========================================================
  // PLACEHOLDERS
  // ========================================================

  document
    .querySelectorAll(
      "[data-i18n-placeholder]"
    )
    .forEach(
      (element) => {

        const key =
          element.dataset
            .i18nPlaceholder;


        const value =
          translations[selected]?.[key];


        if (value) {

          element.placeholder =
            value;

        }

      }
    );


  languageSelect.value =
    selected;


  localStorage.setItem(
    "primitive-earth-language",
    selected
  );


  // ========================================================
  // UPDATE NEWSLETTER MESSAGE
  // ========================================================

  if (
    newsletterState ===
    "success"
  ) {

    showNewsletterSuccess();

  } else {

    clearNewsletterMessage();

  }

}


